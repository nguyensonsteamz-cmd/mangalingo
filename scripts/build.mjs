/**
 * Builds the extension into dist/ in two Vite passes:
 *  1. ESM: service worker + extension pages (side panel, options, offscreen OCR host).
 *  2. IIFE: the content script (MV3 static content scripts cannot be ES modules).
 * Then copies the manifest, icons, bundled data and the OCR runtime (no remote code at runtime).
 */
import { build } from 'vite';
import { cp, mkdir, readFile, rm, writeFile, stat, readdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { sharedConfig, root } from './vite-shared.mjs';

const dist = resolve(root, 'dist');
const pkg = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf8'));
const t0 = Date.now();

if (!existsSync(resolve(root, 'build-data/data/meta.json'))) {
  console.log('[build] generated data missing → running scripts/build-data.mjs');
  await import('./build-data.mjs');
}

await rm(dist, { recursive: true, force: true });

// 1. Pages + background (ES modules)
await build({
  ...sharedConfig(),
  build: {
    outDir: dist,
    emptyOutDir: false,
    target: 'chrome116',
    modulePreload: false,
    sourcemap: false,
    chunkSizeWarningLimit: 2000,
    rollupOptions: {
      input: {
        background: resolve(root, 'src/background/index.ts'),
        sidepanel: resolve(root, 'src/sidepanel/index.html'),
        options: resolve(root, 'src/options/index.html'),
        action: resolve(root, 'src/action/index.html'),
        offscreen: resolve(root, 'src/offscreen/index.html'),
      },
      output: {
        entryFileNames: (c) => (c.name === 'background' ? 'background.js' : 'assets/[name]-[hash].js'),
        chunkFileNames: 'assets/[name]-[hash].js',
        assetFileNames: 'assets/[name]-[hash][extname]',
      },
    },
  },
});

// 2. Content script (single IIFE file; CSS is inlined into the Shadow DOM at runtime)
await build({
  ...sharedConfig(),
  build: {
    outDir: dist,
    emptyOutDir: false,
    target: 'chrome116',
    sourcemap: false,
    lib: {
      entry: resolve(root, 'src/content/index.tsx'),
      formats: ['iife'],
      name: 'MangaLingoContent',
      fileName: () => 'content.js',
    },
    rollupOptions: { output: { inlineDynamicImports: true } },
  },
});

// Vite emits HTML at dist/src/<page>/index.html because root is the repo – flatten to dist/<page>/.
for (const page of ['sidepanel', 'options', 'offscreen', 'action']) {
  const from = join(dist, 'src', page, 'index.html');
  if (existsSync(from)) {
    await mkdir(join(dist, page), { recursive: true });
    const html = (await readFile(from, 'utf8')).replace(/(src|href)="\/assets\//g, '$1="../assets/');
    await writeFile(join(dist, page, 'index.html'), html);
  }
}
await rm(join(dist, 'src'), { recursive: true, force: true });

// 3. Static files
const manifest = JSON.parse(await readFile(resolve(root, 'src/manifest.json'), 'utf8'));
manifest.version = pkg.version;
// optional stable extension id (the public "key" of the extension)
if (process.env.LINGOLENS_EXTENSION_PUBLIC_KEY) manifest.key = process.env.LINGOLENS_EXTENSION_PUBLIC_KEY;
await writeFile(join(dist, 'manifest.json'), JSON.stringify(manifest, null, 2));
// app icons (default logo) – generated by scripts/make-logo-assets.mjs and committed
await cp(join(root, 'assets/icons'), join(dist, 'icons'), { recursive: true });

// OCR runtime – LSTM-only cores (SIMD and non-SIMD) + worker + English model. Nothing is fetched remotely.
const vendor = join(dist, 'vendor', 'tesseract');
await mkdir(join(vendor, 'core'), { recursive: true });
await mkdir(join(vendor, 'lang'), { recursive: true });
await cp(resolve(root, 'node_modules/tesseract.js/dist/worker.min.js'), join(vendor, 'worker.min.js'));
for (const f of ['tesseract-core-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js']) {
  await cp(resolve(root, 'node_modules/tesseract.js-core', f), join(vendor, 'core', f));
}
await cp(
  resolve(root, 'node_modules/@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz'),
  join(vendor, 'lang', 'eng.traineddata.gz'),
);

// Dictionary data generated by scripts/build-data.mjs
await cp(resolve(root, 'build-data/data'), join(dist, 'data'), { recursive: true });

// Third-party notices
const lic = join(dist, 'licenses');
await mkdir(lic, { recursive: true });
const notices = [
  ['node_modules/wordnet-db/LICENSE', 'WordNet-LICENSE.txt'],
  ['node_modules/cmu-pronouncing-dictionary/license', 'cmu-pronouncing-dictionary-LICENSE.txt'],
  ['node_modules/tesseract.js/LICENSE.md', 'tesseract.js-LICENSE.md'],
  ['node_modules/tesseract.js-core/LICENSE', 'tesseract.js-core-LICENSE.txt'],
  ['data/starter/LICENSE.md', 'LingoLens-Starter-LICENSE.md'],
];
for (const [from, to] of notices) {
  if (existsSync(resolve(root, from))) await cp(resolve(root, from), join(lic, to));
  else console.warn(`[build] notice not found: ${from}`);
}

async function dirSize(p) {
  const s = await stat(p);
  if (!s.isDirectory()) return s.size;
  let n = 0;
  for (const e of await readdir(p)) n += await dirSize(join(p, e));
  return n;
}
console.log(`[build] dist/ ready – ${((await dirSize(dist)) / 1048576).toFixed(1)} MB in ${((Date.now() - t0) / 1000).toFixed(1)}s`);
