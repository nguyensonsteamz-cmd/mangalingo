/**
 * Embeds src/reader/reader.js into ios/MangaLingo/WebReader/ReaderScript.swift (a Swift raw string), so the
 * injected script needs no bundle-resource plumbing and always matches the tested source.
 * Run: node scripts/make-reader-script.mjs   (also part of `npm run build:ios-web`)
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const js = await readFile(join(root, 'src/reader/reader.js'), 'utf8');
if (js.includes('"""#')) throw new Error('reader.js contains the Swift raw-string terminator');
const out = join(root, 'ios/MangaLingo/WebReader/ReaderScript.swift');
await mkdir(dirname(out), { recursive: true });
await writeFile(
  out,
  `// GENERATED by scripts/make-reader-script.mjs from src/reader/reader.js – do not edit by hand.
enum ReaderScript {
    static let source = #"""
${js}
"""#
}
`,
);
console.log(`[reader] ${out} (${js.length} chars)`);
