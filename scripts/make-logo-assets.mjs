/**
 * Generates every app icon from the logo definitions in src/ui/logo-data.ts (run after changing a
 * logo; the outputs are committed):
 *   - assets/icons/icon-{16,32,48,128}.png           Chrome extension (default logo, rounded tile)
 *   - ios/MangaLingo/Assets.xcassets/AppIcon*.appiconset  iPhone: default + alternate icons (1024 px)
 *   - android/app/src/main/res/…                     Android adaptive launcher icons (vector)
 * PNGs are drawn with the app's own drawLogo() in headless Chrome.   node scripts/make-logo-assets.mjs
 */
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { transform } from 'esbuild';
import { attach, launch } from './cdp.mjs';

const root = resolve(import.meta.dirname, '..');
const src = await readFile(join(root, 'src/ui/logo-data.ts'), 'utf8');
const js = (await transform(src, { loader: 'ts', format: 'esm' })).code;
const { LOGOS } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const DEFAULT = LOGOS[0].id;
const cap = (s) => s[0].toUpperCase() + s.slice(1);

// ---------------------------------------------------------------- PNG rendering in Chrome
const browser = await launch({ headless: true });
const png = async (id, size, square) => {
  const { targetId } = await browser.send('Target.createTarget', { url: 'about:blank' });
  const page = await attach(browser, targetId);
  const b64 = await page.evaluateMain(`(async () => {
    ${js.replace(/^export /gm, '')}
    const c = new OffscreenCanvas(${size}, ${size});
    drawLogo(c.getContext('2d'), ${JSON.stringify(id)}, ${size}, ${square});
    const blob = await c.convertToBlob({ type: 'image/png' });
    const buf = new Uint8Array(await blob.arrayBuffer());
    let s = ''; for (const b of buf) s += String.fromCharCode(b);
    return btoa(s);
  })()`);
  await browser.send('Target.closeTarget', { targetId });
  return Buffer.from(b64, 'base64');
};

try {
  // Chrome extension icons
  const ext = join(root, 'assets/icons');
  await mkdir(ext, { recursive: true });
  for (const size of [16, 32, 48, 128]) await writeFile(join(ext, `icon-${size}.png`), await png(DEFAULT, size, false));

  // iPhone: AppIcon = default, AppIcon-<Name> = alternates
  const xc = join(root, 'ios/MangaLingo/Assets.xcassets');
  for (const logo of LOGOS) {
    const name = logo.id === DEFAULT ? 'AppIcon' : `AppIcon-${cap(logo.id)}`;
    const dir = join(xc, `${name}.appiconset`);
    await rm(dir, { recursive: true, force: true });
    await mkdir(dir, { recursive: true });
    await writeFile(join(dir, 'icon-1024.png'), await png(logo.id, 1024, true));
    await writeFile(
      join(dir, 'Contents.json'),
      JSON.stringify({ images: [{ filename: 'icon-1024.png', idiom: 'universal', platform: 'ios', size: '1024x1024' }], info: { author: 'xcode', version: 1 } }, null, 2) + '\n',
    );
  }
} finally {
  await browser.close();
}

// ---------------------------------------------------------------- Android adaptive icons (vector)
const res = join(root, 'android/app/src/main/res');
await mkdir(join(res, 'drawable'), { recursive: true });
await mkdir(join(res, 'mipmap-anydpi-v26'), { recursive: true });
const scale = 0.85; // keep the artwork inside the 66 dp safe zone of the 108 dp canvas
const offset = (108 - 64 * scale) / 2;
let colors = '<resources>\n';
for (const logo of LOGOS) {
  const paths = logo.paths
    .map((p) => `        <path android:fillColor="${p.fill}"${p.rule === 'evenodd' ? ' android:fillType="evenOdd"' : ''} android:pathData="${p.d}" />`)
    .join('\n');
  await writeFile(
    join(res, `drawable/ic_logo_${logo.id}_fg.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<!-- generated by scripts/make-logo-assets.mjs – edit src/ui/logo-data.ts instead -->
<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">
    <group android:translateX="${offset.toFixed(2)}" android:translateY="${offset.toFixed(2)}" android:scaleX="${scale}" android:scaleY="${scale}">
${paths}
    </group>
</vector>
`,
  );
  await writeFile(
    join(res, `mipmap-anydpi-v26/ic_launcher_${logo.id}.xml`),
    `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/logo_${logo.id}_bg" />
    <foreground android:drawable="@drawable/ic_logo_${logo.id}_fg" />
</adaptive-icon>
`,
  );
  colors += `    <color name="logo_${logo.id}_bg">${logo.bg}</color>\n`;
}
await writeFile(join(res, 'values/logo_colors.xml'), colors + '</resources>\n');
console.log(`[logos] ${LOGOS.map((l) => l.id).join(', ')} → assets/icons, iOS app icons, Android launcher icons`);
